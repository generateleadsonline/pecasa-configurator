#!/usr/bin/env python3
"""Build the self-contained brand assets for the design PDF: src/configurator-pdf-assets.js.

- Fonts: Barlow and Barlow Condensed TTF subsets from tools/fonts/pdf/ (run tools/fonts.py).
- Logos: Pecasa's own planner logo (public/assets/brand/pecasa-logo-*.svg), rasterised to PNG
  with headless Google Chrome at print resolution.
- Photos: one real Pecasa photograph or official render per style, listed with its source
  URL in tools/pdf-photos.json. Used only when a device cannot render the 3D views.

Run: python3 tools/build-pdf-assets.py   (needs Pillow and Google Chrome)
"""
import base64
import hashlib
import io
import json
import os
import subprocess
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'src' / 'configurator-pdf-assets.js'
CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
FONTS = {'regular': 'barlow-400.ttf', 'medium': 'barlow-500.ttf', 'semibold': 'barlow-600.ttf',
         'heading': 'barlow-condensed-700.ttf', 'headingSemi': 'barlow-condensed-600.ttf'}
PHOTO_WIDTH = 760


def b64(data):
    return base64.b64encode(data).decode('ascii')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def rasterise(svg_path, width):
    """SVG to a trimmed transparent PNG through headless Chrome."""
    svg = svg_path.read_text(encoding='utf-8')
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / 'logo.html'
        page.write_text(f'<!doctype html><html><body style="margin:0;background:transparent">'
                        f'<img src="file://{svg_path}" style="display:block;width:{width}px"></body></html>')
        shot = Path(tmp) / 'logo.png'
        subprocess.run([CHROME, '--headless=new', '--disable-gpu', '--hide-scrollbars', f'--user-data-dir={tmp}/profile',
                        '--default-background-color=00000000', f'--window-size={width + 40},{width}',
                        f'--screenshot={shot}', f'file://{page}'], check=True, capture_output=True, timeout=60)
        img = Image.open(shot).convert('RGBA')
    img = img.crop(img.getbbox())
    out = io.BytesIO()
    img.save(out, 'PNG', optimize=True)
    return out.getvalue(), img.size


fonts, info = {}, {'fonts': {}, 'logos': {}, 'photos': {}}
for key, name in FONTS.items():
    data = (ROOT / 'tools' / 'fonts' / 'pdf' / name).read_bytes()
    fonts[key] = b64(data)
    info['fonts'][key] = {'source': f'tools/fonts/pdf/{name}', 'sha256': sha(data), 'bytes': len(data)}

logos = {}
for variant in ['positive', 'negative']:
    src = ROOT / 'public' / 'assets' / 'brand' / f'pecasa-logo-{variant}.svg'
    png, (w, h) = rasterise(src, 1200)
    logos[variant] = 'data:image/png;base64,' + b64(png)
    info['logos'][variant] = {'source': str(src.relative_to(ROOT)), 'sourceSha256': sha(src.read_bytes()), 'bytes': len(png), 'width': w, 'height': h, 'ratio': w / h}

photos = {}
manifest = json.loads((ROOT / 'tools' / 'pdf-photos.json').read_text())
for style, entry in manifest.items():
    path = ROOT / entry['file']
    img = Image.open(path).convert('RGB')
    if img.width > PHOTO_WIDTH:
        img = img.resize((PHOTO_WIDTH, round(img.height * PHOTO_WIDTH / img.width)), Image.LANCZOS)
    out = io.BytesIO()
    img.save(out, 'JPEG', quality=82, optimize=True, progressive=False)
    photos[style] = 'data:image/jpeg;base64,' + b64(out.getvalue())
    info['photos'][style] = {'source': entry['file'], 'url': entry['url'], 'bytes': out.tell(), 'width': img.width, 'height': img.height}

OUTPUT.write_text(
    '// Generated by tools/build-pdf-assets.py. Do not edit by hand.\n'
    '// Barlow fonts (SIL OFL 1.1), Pecasa\'s planner logo and Pecasa photography, embedded so the PDF\n'
    '// needs no network requests. Sources and hashes are in PDF_ASSET_INFO.\n'
    f'export const PDF_FONTS = {json.dumps(fonts)};\n'
    f'export const PDF_LOGO = {json.dumps(logos["positive"])};\n'
    f'export const PDF_LOGO_NEGATIVE = {json.dumps(logos["negative"])};\n'
    f'export const PDF_LOGO_RATIO = {info["logos"]["positive"]["ratio"]:.4f};\n'
    f'export const PDF_STYLE_PHOTOS = {json.dumps(photos)};\n'
    f'export const PDF_ASSET_INFO = {json.dumps(info)};\n', encoding='utf-8')
print(f'wrote {OUTPUT.relative_to(ROOT)}: {OUTPUT.stat().st_size:,} bytes')
